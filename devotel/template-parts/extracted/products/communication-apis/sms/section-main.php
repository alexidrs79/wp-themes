  (function() {
    // Tab switching functionality
    const tabs = document.querySelectorAll('.sms-api-tab');
    const codeContents = document.querySelectorAll('.sms-api-code-content');
    const lineNumbers = document.getElementById('line-numbers');
    
    function updateLineNumbers(activeContent) {
        if (!lineNumbers || !activeContent) return;
        
        // Count lines by counting <br /> tags in the HTML content
        // This matches how the code is actually rendered
        const htmlContent = activeContent.innerHTML;
        const brMatches = htmlContent.match(/<br\s*\/?>/gi);
        // Each <br /> represents a line break, so total lines = number of <br /> tags + 1
        const lineCount = brMatches ? brMatches.length + 1 : 1;
        
        // Generate line numbers dynamically
        let lineNumbersHtml = '';
        for (let i = 1; i <= lineCount; i++) {
            lineNumbersHtml += i + '<br />';
        }
        lineNumbers.innerHTML = lineNumbersHtml;
    }
    
    function switchTab(clickedTab) {
        const tabName = clickedTab.getAttribute('data-tab');
        
        // Update all tabs
        tabs.forEach(t => {
            const textElement = t.querySelector('.sms-api-text, .sms-api-text2');
            
            if (t === clickedTab) {
                // Make clicked tab active
                t.classList.remove('sms-api-code-snippet-tabs2');
                t.classList.add('sms-api-code-snippet-tabs', 'active');
                if (textElement) {
                    textElement.classList.remove('sms-api-text2');
                    textElement.classList.add('sms-api-text');
                }
              } else {
                // Make other tabs inactive
                t.classList.remove('sms-api-code-snippet-tabs', 'active');
                t.classList.add('sms-api-code-snippet-tabs2');
                if (textElement) {
                    textElement.classList.remove('sms-api-text');
                    textElement.classList.add('sms-api-text2');
                }
            }
        });
        
        // Update code content visibility
        let activeContentElement = null;
        codeContents.forEach(content => {
            if (content.getAttribute('data-content') === tabName) {
                content.classList.add('active');
                activeContentElement = content;
              } else {
                content.classList.remove('active');
            }
        });
        
        // Update line numbers
        updateLineNumbers(activeContentElement);
    }
    
    // Initialize line numbers for default active tab
    const defaultActiveContent = document.querySelector('.sms-api-code-content.active');
    if (defaultActiveContent) {
        updateLineNumbers(defaultActiveContent);
    }
    
    // Add click event listeners
    tabs.forEach(tab => {
        tab.addEventListener('click', function() {
            switchTab(this);
        });
    });
  })();
